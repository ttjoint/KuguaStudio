/**
 * 小组件布局决策测试
 *
 * 这里测的都是「谁该占多宽、放哪儿、排第几」这类判断。它们之前写在
 * `parts/19-widgets.ts` 里，那是个依赖 DOM 的渲染模块，导入就要有 document，
 * 所以一直没测——而实际上最容易出错的恰恰是这些判断，不是画的那几行。
 */
import { describe, expect, it } from "vitest";
import {
  决定外形,
  决定区域,
  排序键,
  取覆盖,
  取展示预设,
  宽度上限,
  窄窗阈值,
  极窄阈值,
  type 小组件配置节,
} from "../src/widget-layout.js";

const 项 = (显著度?: "primary" | "normal" | "secondary") => ({ 键: "a.b", 显著度 });

describe("宽度上限", () => {
  it("宽屏允许大卡", () => {
    expect(宽度上限(1400)).toBe("大卡");
    expect(宽度上限(窄窗阈值)).toBe("大卡");
  });

  it("窄窗降成横条", () => {
    expect(宽度上限(窄窗阈值 - 1)).toBe("横条");
    expect(宽度上限(极窄阈值)).toBe("横条");
  });

  it("极窄一律窄条", () => {
    expect(宽度上限(极窄阈值 - 1)).toBe("窄条");
    expect(宽度上限(320)).toBe("窄条");
  });
});

describe("决定外形：用户覆盖优先", () => {
  it("显式指定时无视窗口宽度", () => {
    // 用户说了算：他显式选了大卡，即使窗口很窄也照办。
    // 这和「自动推算」是两件事，混在一起会让用户觉得设置不生效。
    expect(决定外形(项("secondary"), { 外形: "大卡" }, "自动", 320)).toBe("大卡");
    expect(决定外形(项("primary"), { 外形: "窄条" }, "自动", 1920)).toBe("窄条");
  });
});

describe("决定外形：预设优先于显著度", () => {
  it("紧凑预设把 primary 也压成窄条", () => {
    expect(决定外形(项("primary"), {}, "紧凑", 1920)).toBe("窄条");
  });

  it("详细预设把 secondary 也放大成大卡", () => {
    expect(决定外形(项("secondary"), {}, "详细", 1920)).toBe("大卡");
  });

  it("仅状态栏等同最紧凑", () => {
    expect(决定外形(项("primary"), {}, "仅状态栏", 1920)).toBe("窄条");
  });
});

describe("决定外形：宽度是上限不是优先级", () => {
  it("窄窗把 primary 的大卡压成横条", () => {
    // 这就是这条规则存在的理由：1366 宽的笔记本 + 侧栏展开时，
    // 三个 primary 大卡（各 150px 起）会把顶部条挤成两行甚至溢出。
    expect(决定外形(项("primary"), {}, "自动", 600)).toBe("横条");
  });

  it("极窄再压成窄条", () => {
    expect(决定外形(项("primary"), {}, "自动", 400)).toBe("窄条");
  });

  it("宽度不会把东西放大", () => {
    // secondary 本来就该窄，宽屏也不能给它抬成大卡
    expect(决定外形(项("secondary"), {}, "自动", 1920)).toBe("窄条");
    expect(决定外形(项(), {}, "紧凑", 1920)).toBe("窄条");
  });

  it("默认显著度（normal）在宽屏是横条", () => {
    expect(决定外形(项(), {}, "自动", 1400)).toBe("横条");
    expect(决定外形(项(undefined), {}, "自动", 1400)).toBe("横条");
  });
});

describe("决定区域", () => {
  it("用户覆盖优先", () => {
    expect(决定区域(项("primary"), { 区域: "侧栏" })).toBe("侧栏");
  });

  it("按显著度分布", () => {
    expect(决定区域(项("primary"), {})).toBe("顶部");
    expect(决定区域(项("secondary"), {})).toBe("状态栏");
    expect(决定区域(项(), {})).toBe("顶部");
  });
});

describe("排序键", () => {
  it("用户顺序优先于显著度", () => {
    // 用户把 secondary 拖到最前面，它就该排第一
    expect(排序键(项("secondary"), { 顺序: 0 })).toBeLessThan(
      排序键(项("normal"), {}),
    );
  });

  it("无覆盖时按显著度（primary < normal < secondary）", () => {
    expect(排序键(项("primary"), {})).toBeLessThan(排序键(项("normal"), {}));
    expect(排序键(项("normal"), {})).toBeLessThan(排序键(项("secondary"), {}));
  });

  it("顺序 0 不会被当成「没有顺序」", () => {
    // 用 `覆盖.顺序 || 默认值` 写就把 0 当成假值了，表现是第一项永远排不上
    expect(排序键(项("primary"), { 顺序: 0 })).toBe(0);
  });
});

describe("取覆盖 / 取展示预设", () => {
  const 配置: 小组件配置节 = {
    当前方案: "日常",
    方案: {
      日常: { 展示: "紧凑", 覆盖: { "a.b": { 隐藏: true } } },
      专注: { 展示: "详细", 覆盖: { "a.b": { 外形: "窄条" } } },
    },
  };

  it("取当前方案的覆盖项", () => {
    expect(取覆盖(配置, "a.b")).toEqual({ 隐藏: true });
    expect(取展示预设(配置)).toBe("紧凑");
  });

  it("别的方案不影响当前方案", () => {
    const 切过 = { ...配置, 当前方案: "专注" };
    expect(取覆盖(切过, "a.b")).toEqual({ 外形: "窄条" });
    expect(取展示预设(切过)).toBe("详细");
  });

  it("配置为 null / 方案不存在时给安全默认值", () => {
    expect(取覆盖(null, "a.b")).toEqual({});
    expect(取展示预设(null)).toBe("自动");
    expect(取覆盖({ 当前方案: "不存在", 方案: {} }, "a.b")).toEqual({});
  });

  it("没有这一项的覆盖时返回空对象而不是 undefined", () => {
    expect(取覆盖(配置, "不存在.的")).toEqual({});
  });
});
