/**
 * 小组件的布局决策（纯函数）
 *
 * 从 `parts/19-widgets.ts` 抽出来的原因：那是个依赖 DOM 的渲染模块，导入它
 * 就要有 `document`，而真正容易出错、又最应该被测的恰恰是这里的**决策**——
 * 谁该占多宽、在哪个区域、排第几。
 *
 * 这一层没有副作用：给一组输入，返回一个结论。
 */

/** 用户对单个小组件的覆盖 */
export interface 布局覆盖 {
  隐藏?: boolean;
  顺序?: number;
  外形?: "大卡" | "横条" | "窄条";
  区域?: "顶部" | "侧栏" | "状态栏";
}

/** 一套布局方案 */
export interface 布局方案 {
  展示?: "自动" | "紧凑" | "详细" | "仅状态栏";
  覆盖?: Record<string, 布局覆盖>;
}

/** 落盘的 widgets 配置节 */
export interface 小组件配置节 {
  当前方案: string;
  方案: Record<string, 布局方案>;
}

/** 决策只需要这几个字段 */
export interface 决策输入 {
  键: string;
  显著度?: "primary" | "normal" | "secondary";
}

export type 展示预设 = NonNullable<布局方案["展示"]>;
export type 外形 = NonNullable<布局覆盖["外形"]>;
export type 区域 = NonNullable<布局覆盖["区域"]>;

/**
 * 窄窗口阈值（像素）。
 *
 * 低于这个宽度时，「大卡」降级成「横条」而不是直接变窄条：
 * 大卡的价值是数字大字 + 环形图，挤到 100px 以内两样都看不清，
 * 但完全退成一行小字又浪费了本来还够用的横向空间。
 */
export const 窄窗阈值 = 720;
/** 更窄时连横条也撑不住，一律退成窄条 */
export const 极窄阈值 = 480;

/**
 * 按当前窗口宽度得出「最多能用多大外形」。
 *
 * 为什么需要它：`primary` 组件在笔记本 1366 宽 + 侧栏展开时，
 * 三个大卡（各 150px 起）会把顶部条挤成两行甚至溢出。
 * 显著度表达的是「这个指标重要」，不是「它该占多宽」——
 * 屏幕放不下时，重要性和宽度必须解耦。
 */
export function 宽度上限(宽: number): 外形 {
  if (宽 < 极窄阈值) return "窄条";
  if (宽 < 窄窗阈值) return "横条";
  return "大卡";
}

const 外形档位: Record<外形, number> = { 大卡: 3, 横条: 2, 窄条: 1 };

/**
 * 决定一个小组件的最终外形。
 *
 * 优先级：用户覆盖 > 形态预设 > 显著度 > 窗口宽度。
 * 显著度只是**输入**，不是输出——这是职责分界的落点。
 *
 * 宽度放在最后当**上限**，不是优先级：用户显式指定 `外形: "大卡"` 时
 * 仍然尊重（他大概知道自己在干什么），只是自动推算的结果会被压小。
 * 这里和覆盖的区别在于「谁说的话算数」——用户说了就听用户的。
 */
export function 决定外形(
  项: 决策输入,
  覆盖: 布局覆盖,
  预设: 展示预设,
  窗口宽: number,
): 外形 {
  // 用户显式指定：无条件尊重，不看宽度
  if (覆盖.外形) return 覆盖.外形;

  let 拟: 外形;
  if (预设 === "紧凑" || 预设 === "仅状态栏") 拟 = "窄条";
  else if (预设 === "详细") 拟 = "大卡";
  else if (项.显著度 === "primary") 拟 = "大卡";
  else if (项.显著度 === "secondary") 拟 = "窄条";
  else 拟 = "横条";

  // 窗口宽度只往下压，不往上抬
  const 限 = 宽度上限(窗口宽);
  return 外形档位[拟] <= 外形档位[限] ? 拟 : 限;
}

/** 决定放在哪个区域（同样只受用户覆盖与显著度影响，不看宽度） */
export function 决定区域(项: 决策输入, 覆盖: 布局覆盖): 区域 {
  if (覆盖.区域) return 覆盖.区域;
  if (项.显著度 === "primary") return "顶部";
  if (项.显著度 === "secondary") return "状态栏";
  return "顶部";
}

/** 排序键：用户覆盖的顺序优先，其次按显著度 */
export function 排序键(项: 决策输入, 覆盖: 布局覆盖): number {
  if (typeof 覆盖.顺序 === "number") return 覆盖.顺序;
  const 显著度权重: Record<string, number> = { primary: 0, normal: 100, secondary: 200 };
  return 显著度权重[项.显著度 ?? "normal"] ?? 100;
}

/** 取某方案下某个小组件的覆盖项 */
export function 取覆盖(配置: 小组件配置节 | null, 键: string): 布局覆盖 {
  if (!配置) return {};
  const 方案 = 配置.方案[配置.当前方案];
  return 方案?.覆盖?.[键] ?? {};
}

/** 当前方案的形态预设 */
export function 取展示预设(配置: 小组件配置节 | null): 展示预设 {
  if (!配置) return "自动";
  return 配置.方案[配置.当前方案]?.展示 ?? "自动";
}
