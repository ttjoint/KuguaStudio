/**
 * 图片动作声明表 —— 37 个动作的唯一真相。
 *
 * ## 为什么要这张表
 *
 * 改造前每个动作有三份互相独立的描述：
 *   1. `能力清单` 里一行 `图片能力("resize", "缩放", "按宽度/高度或比例缩放")`
 *   2. 处理函数里内联的 `as { scaleX?: number; ... }` 类型字面量
 *   3. `取图Buffer(params)` / 各种 `?? 默认值` 散落在函数体里
 *
 * 三份之间没有任何强制约束。加一个新动作要在三处改，漏一处不会报错——
 * 参数改了但能力清单没改，界面就按旧 schema 生成控件，用户填的字段
 * 处理函数根本读不到，表现为「参数不生效」。这类 bug 不会有任何日志。
 *
 * 更要紧的是：要给它做编辑页（UI 拖滑块），就得知道每个参数是什么
 * 控件、范围多少、默认值是多少、改一下能不能实时预览。这些信息当时
 * 全在人的脑子里，代码里读不出来。
 *
 * ## 表驱动之后
 *
 * - **能力清单**：由声明生成（`能力声明数组()`）
 * - **JSON Schema**：由声明生成（给 MCP / 外部调用）
 * - **参数校验**：由声明生成（`归一参数()`）
 * - **编辑页控件**：由声明生成（前端读 `/api/image/actions` 拿到本表）
 * - **聊天框参数提示**：读同一份
 *
 * 加新动作只写一条声明 + 一个执行函数。
 *
 * ## 字段含义
 *
 * `参数` 里每一项的 `类型` 不只是 TS 类型，还带控件语义：
 *   - `number`  → 有 最小/最大/步进 就出滑块，否则出数字框
 *   - `string`  → 出文本框；`选择` 非空出下拉框
 *   - `boolean` → 出开关
 *   - `images`  → 多图槽位（不是文本框！见下）
 *
 * `源图` 表示「这个动作要一张输入图」：GUI 侧就是主图槽位；
 * `多图` 表示「要 N 张图」，GUI 侧是可增删的图片列表。
 * 两者都**不进参数面板的输入框**，走附件槽位——一张图塞不进文本框。
 */

/** 参数控件类型 */
export type 参数类型 = "number" | "string" | "boolean" | "images";

/** 一个参数的完整声明 */
export interface 参数声明 {
  /** 参数名（与执行函数读取的键名一致） */
  键: string;
  /** 界面标签 */
  标题: string;
  类型: 参数类型;
  /** 默认值。不填表示必填（GUI 会拦一次） */
  默认?: number | string | boolean;
  /**
   * 界面初始值，缺省用 `默认`。
   *
   * 两者的区别是真实存在的：`rotate` 的协议默认值是 0（不传就不转），
   * 但界面上开局就是「旋转 0 度」毫无意义——用户点进旋转就是想让图转起来。
   * 所以界面给 90，协议仍保持 0，这样聊天框说「旋转」不传角度时行为不变。
   */
  界面默认?: number | string | boolean;
  /** 说明 */
  说明?: string;
  // —— 仅 number 有效 ——
  最小?: number;
  最大?: number;
  步进?: number;
  /** 数字也可以是离散档位（如 mode 1-4） */
  档位?: { 值: number; 标签: string }[];
  // —— 仅 string 有效 ——
  /** 非空则出下拉框 */
  选择?: { 值: string; 标签: string }[];
}

/**
 * 实时预览能力。
 *
 * 这是编辑页「拖滑块有反馈」的依据：有 `预览` 的动作，前端先在本地用
 * CSS / Canvas 做近似预览，松手才真调后端（因为一次 magick 调用要
 * 190ms+，实时调后端做不到 60fps）。
 *
 * - `css-transform`：可用 CSS `transform` 直接预览（旋转/翻转/缩放）
 * - `css-filter`：可用 CSS `filter` 近似（反色/灰度）
 * - `overlay`：用 Canvas 叠线框/遮罩预览（切边/网格/切割）
 * - `none`：无法本地预览，按钮触发 + 进度提示
 */
export type 预览方式 = "css-transform" | "css-filter" | "overlay" | "none";

/** 动作分组（编辑页按组显示） */
export type 动作分组 = "几何" | "色彩" | "特效" | "GIF" | "多图" | "生成" | "信息";

/** 一个动作的完整声明 */
export interface 动作声明 {
  /** 动作名，最终能力名是 `image.<动作>` */
  动作: string;
  /** 界面标题 */
  标题: string;
  /** 说明 */
  说明: string;
  /** 分组 */
  分组: 动作分组;
  /** 参数列表；空数组表示无需参数 */
  参数: 参数声明[];
  /** 是否需要一张输入图 */
  源图?: boolean;
  /** 实时预览方式，缺省 none */
  预览?: 预览方式;
  /**
   * 是否在编辑页默认展示。
   *
   * 34 个动作全铺在界面上是灾难——大部分（反色、灰度、翻转）点一下就完事，
   * 不需要参数面板也不需要预览。这里标出「值得做成交互」的约 20 个，
   * 其余的仍在聊天框/命令行可用，只是编辑页折叠到「更多」里。
   */
  常用?: boolean;
}

