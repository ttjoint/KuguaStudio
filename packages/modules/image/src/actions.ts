/** 全部动作声明（顺序即编辑页展示顺序） */
export const 动作声明表: 动作声明[] = [...交互动作, ...一键动作];

/** 按动作名查声明 */
export function 查声明(动作: string): 动作声明 | undefined {
  return 动作声明表.find((d) => d.动作 === 动作);
}

/** 这个动作是否要源图（含多图） */
export function 需要源图(d: 动作声明): boolean {
  return d.源图 === true || d.参数.some((p) => p.类型 === "images");
}

/**
 * 参数类型 → JSON Schema 片段。
 *
 * 给 MCP / 外部调用用。刻意保持最小：外部工具不需要知道"步进 0.05"
 * 这种界面细节，只需要知道类型和范围。
 */
function 参数schema(p: 参数声明): Record<string, unknown> {
  switch (p.类型) {
    case "number":
      return {
        type: "number",
        ...(p.最小 !== undefined ? { minimum: p.最小 } : {}),
        ...(p.最大 !== undefined ? { maximum: p.最大 } : {}),
        ...(p.默认 !== undefined ? { default: p.默认 } : {}),
        ...(p.说明 ? { description: p.说明 } : {}),
      };
    case "boolean":
      return {
        type: "boolean",
        ...(p.默认 !== undefined ? { default: p.默认 } : {}),
        ...(p.说明 ? { description: p.说明 } : {}),
      };
    case "images":
      return {
        type: "array",
        items: { type: "string" },
        ...(p.说明 ? { description: p.说明 } : {}),
      };
    case "string":
    default: {
      const 基: Record<string, unknown> = {
        type: "string",
        ...(p.默认 !== undefined ? { default: p.默认 } : {}),
        ...(p.说明 ? { description: p.说明 } : {}),
      };
      if (p.选择?.length) 基.enum = p.选择.map((o) => o.值);
      return 基;
    }
  }
}

/**
 * 生成单个动作的参数 JSON Schema。
 *
 * 会把 `base64` / `path` 一起带上——聊天框、MCP、外部调用都走这两个字段传图，
 * 只有编辑页用多图槽位（`images`），那是界面层的事。
 */
export function 动作schema(d: 动作声明): Record<string, unknown> {
  const properties: Record<string, unknown> = {};
  const required: string[] = [];
  for (const p of d.参数) {
    properties[p.键] = 参数schema(p);
    if (p.默认 === undefined && p.类型 !== "images") required.push(p.键);
  }
  if (需要源图(d)) {
    properties.base64 = { type: "string", description: "图片 base64（与 path 二选一）" };
    properties.path = { type: "string", description: "图片路径（与 base64 二选一）" };
  }
  return {
    type: "object",
    properties,
    ...(required.length ? { required } : {}),
  };
}

/**
 * 归一参数：按声明夹取范围、补默认值。
 *
 * 为什么不直接信任调用方：
 *   - 界面滑块理论上不会越界，但聊天框是**用户手打**的（「旋转 500 度」），
 *     外部 MCP 调用也可能乱传。夹取比报错友好，也复刻了原实现的宽容行为。
 *   - 原实现各动作各自 `?? 默认值`，散落 30 多处，改一处漏一处。
 *
 * **不看 base64 / path**：那是图不是参数，原样透传。
 */
export function 归一参数(d: 动作声明, 原始: unknown): Record<string, unknown> {
  const 入 = (原始 ?? {}) as Record<string, unknown>;
  const 出: Record<string, unknown> = {};
  for (const p of d.参数) {
    const 值 = 入[p.键];
    if (p.类型 === "images") {
      // 多图不动内容，只保证是字符串数组
      if (Array.isArray(值)) 出[p.键] = 值.filter((x): x is string => typeof x === "string");
      continue;
    }
    if (值 === undefined || 值 === null || 值 === "") {
      出[p.键] = p.默认;
      continue;
    }
    if (p.类型 === "number") {
      const n = Number(值);
      if (!Number.isFinite(n)) {
        出[p.键] = p.默认;
        continue;
      }
      let v = n;
      if (p.最小 !== undefined && v < p.最小) v = p.最小;
      if (p.最大 !== undefined && v > p.最大) v = p.最大;
      出[p.键] = v;
      continue;
    }
    if (p.类型 === "boolean") {
      出[p.键] = 值 === true || 值 === "true" || 值 === 1 || 值 === "1";
      continue;
    }
    出[p.键] = String(值);
  }
  // 图相关字段原样透传，不进上面的循环
  for (const k of ["base64", "path", "images"]) {
    if (入[k] !== undefined && 出[k] === undefined) 出[k] = 入[k];
  }
  return 出;
}
