/**
 * `dream` 模块的确定性测试。
 *
 * 「解梦」正文靠 DScript 脚本查表，语料改了结果就变。但入口的关键词提取
 * 是确定性解析，而且直接决定「查得中还是查不中」：
 *
 *   梦见蛇 / 梦到蛇 / 解梦蛇  → 关键词都是「蛇」
 *   蛇（没有前缀）            → 关键词是「蛇」本身
 *   梦见（后面什么都没有）     → 回落成「梦见」，查不到该给「我不知道」
 *
 * 前缀漏一条，用户输入就会被整体当成关键词去查表，结果永远是「我不知道」，
 * 而日志里什么都没有。
 */

import { describe, expect, it, vi } from "vitest";

vi.mock("@kugua/random", () => ({
  NextInt: (max?: number) => Math.floor(Math.random() * (max ?? 1)),
}));

const { 解析关键词 } = await import("../src/index.js");

describe("dream 解析关键词", () => {
  it("梦见蛇 → 蛇", () => {
    expect(解析关键词("梦见蛇")).toBe("蛇");
  });

  it("梦到蛇 → 蛇", () => {
    expect(解析关键词("梦到蛇")).toBe("蛇");
  });

  it("解梦蛇 → 蛇", () => {
    expect(解析关键词("解梦蛇")).toBe("蛇");
  });

  it("前缀后有空格也认得", () => {
    expect(解析关键词("梦见 蛇")).toBe("蛇");
    expect(解析关键词("梦见  蛇")).toBe("蛇");
  });

  it("没有前缀时整个原文都是关键词", () => {
    expect(解析关键词("蛇")).toBe("蛇");
    expect(解析关键词("考试迟到")).toBe("考试迟到");
  });

  it("首尾空白被去掉", () => {
    expect(解析关键词("  梦见蛇  ")).toBe("蛇");
  });

  it("只有前缀时回落成前缀本身（不该返回空串）", () => {
    // `(.+)` 要求至少一个字符，所以「梦见」单独出现匹配不上，
    // 关键词退回「梦见」——查表必然查不到，于是给出「我不知道」。
    // 这里锁住该行为：若改成返回空串，调用方会拿空关键词去查，
    // 可能命中奇怪的表项。
    expect(解析关键词("梦见")).toBe("梦见");
    expect(解析关键词("解梦")).toBe("解梦");
  });

  it("空串返回空串", () => {
    expect(解析关键词("")).toBe("");
    expect(解析关键词("   ")).toBe("");
  });

  it("前缀在中间时不算前缀", () => {
    expect(解析关键词("我梦见蛇")).toBe("我梦见蛇");
  });

  it("关键词本身含「梦」字也能正确剥离前缀", () => {
    expect(解析关键词("梦见做梦")).toBe("做梦");
  });
});
