/**
 * `food` 模块的确定性测试。
 *
 * 「今天吃什么」的正文靠 DScript 脚本随机拼（语料一改就变），不适合逐字对齐。
 * 但入口这一段是**确定性解析**，而且是静默降级的重灾区：
 *
 *  - 「晚上喝什么」→ 时间=晚上、动词=喝
 *  - 「吃什么」→ 时间被空串顶掉，应当回落「今天」
 *  - 匹配不上时**不能**把调用方显式给的 time/verb 顶掉
 *
 * 还有 `人称互换`：先把我换占位符再换你，顺序写反就变成全员「我」。
 */

import { describe, expect, it, vi } from "vitest";

vi.mock("@kugua/random", () => ({
  NextInt: (max?: number) => Math.floor(Math.random() * (max ?? 1)),
}));

const { 人称互换, 解析文本 } = await import("../src/index.js");

describe("food 人称互换", () => {
  it("我 → 你，你 → 我（互换）", () => {
    expect(人称互换("我")).toBe("你");
    expect(人称互换("你")).toBe("我");
  });

  it("一句话里两个都换，不会串成同一个", () => {
    // 关键在顺序：先把「我」换成占位符，再换「你」→「我」，最后占位符→「你」。
    // 直接 replace 两遍会让「我」先变「你」再变回「我」，等于没换。
    expect(人称互换("我请你")).toBe("你请我");
  });

  it("原文里本来就有【W】也能正常处理", () => {
    // 占位符是内部约定，用户文本里出现时行为应当是确定的（不崩、有输出）
    expect(typeof 人称互换("【W】我")).toBe("string");
  });

  it("不含人称的文本原样返回", () => {
    expect(人称互换("今天吃火锅")).toBe("今天吃火锅");
  });

  it("空串返回空串", () => {
    expect(人称互换("")).toBe("");
  });
});

describe("food 解析文本", () => {
  it("「晚上喝什么」→ 时间=晚上、动词=喝", () => {
    expect(解析文本("晚上喝什么")).toEqual({ time: "晚上", verb: "喝" });
  });

  it("「中午吃什么呢」这种带「呢」的匹配不上（正则要求以「什么」结尾）", () => {
    expect(解析文本("中午吃什么呢")).toBe(null);
  });

  it("「吃什么」→ 时间部分为空，回落「今天」，动词=吃", () => {
    expect(解析文本("吃什么")).toEqual({ time: "今天", verb: "吃" });
  });

  it("「现在吃什么」→ 时间=现在", () => {
    expect(解析文本("现在吃什么")).toEqual({ time: "现在", verb: "吃" });
  });

  it("前缀都没有时返回 null（让调用方保留自己的 time/verb）", () => {
    expect(解析文本("随便")).toBe(null);
    expect(解析文本("")).toBe(null);
    expect(解析文本("   ")).toBe(null);
  });

  it("首尾空白被去掉", () => {
    expect(解析文本("  晚上喝什么  ")).toEqual({ time: "晚上", verb: "喝" });
  });

  it("时间部分只剩空白时回落「今天」", () => {
    expect(解析文本(" 吃什么")).toEqual({ time: "今天", verb: "吃" });
  });

  it("动词取的是「什么」前的那**一个**字", () => {
    // 「吃喝什么」→ 时间=吃、动词=喝
    expect(解析文本("吃喝什么")).toEqual({ time: "吃", verb: "喝" });
  });
});
