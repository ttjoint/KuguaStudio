/**
 * `text` 模块的确定性测试。
 *
 * 这个模块 15 项能力里，大部分是「拿语料随机拼」（狗屁不通、营销号、云杰说道），
 * 逐字对齐没有意义——语料一改就全红。但有四段**纯逻辑**是确定性的、
 * 而且边界特别密，恰恰是最容易写错又最不容易被发现的部分：
 *
 *  1. `中文数字转整数`——「十九」「二十」「廿」「十一」这些进位很容易算错，
 *     算错了只是日期变成别的日子，不当场报错
 *  2. `解析日期`——「大前天」「大大后天」「三月五」「3月5日」，边界靠正则，
 *     写漏一条就静默回落到「今天」
 *  3. `从文本找关键词`——最长匹配 + 去重保序，写错会出现重复项或错项
 *  4. `规范参数`——中文指令传 `参数文本`，能力调用传 `文本`，不补齐就取不到值
 *
 * 时间相关的用 `vi.setSystemTime` 冻结，否则「今天」会随机器时钟漂移。
 */

import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

vi.mock("@kugua/random", () => ({
  NextInt: (max?: number) => Math.floor(Math.random() * (max ?? 1)),
}));

const { 规范参数, 从文本找关键词, 中文数字转整数, 解析日期 } = await import(
  "../src/index.js"
);

describe("text 中文数字转整数", () => {
  it("纯阿拉伯数字直接取整", () => {
    expect(中文数字转整数("5")).toBe(5);
    expect(中文数字转整数("12")).toBe(12);
    expect(中文数字转整数("100")).toBe(100);
  });

  it("单个汉字数字", () => {
    expect(中文数字转整数("一")).toBe(1);
    expect(中文数字转整数("九")).toBe(9);
  });

  it("〇 / 零 都算 0", () => {
    expect(中文数字转整数("〇")).toBe(0);
    expect(中文数字转整数("零")).toBe(0);
  });

  it("两 等于 二", () => {
    expect(中文数字转整数("两")).toBe(2);
  });

  it("十几：十一 / 十二 / 十九", () => {
    expect(中文数字转整数("十")).toBe(10);
    expect(中文数字转整数("十一")).toBe(11);
    expect(中文数字转整数("十二")).toBe(12);
    expect(中文数字转整数("十九")).toBe(19);
  });

  it("几十：二十 / 三十 这种整十", () => {
    expect(中文数字转整数("二十")).toBe(20);
    expect(中文数字转整数("三十")).toBe(30);
  });

  it("廿 / 卅 / 卌 是 20 / 30 / 40", () => {
    expect(中文数字转整数("廿")).toBe(20);
    expect(中文数字转整数("卅")).toBe(30);
    expect(中文数字转整数("卌")).toBe(40);
  });

  it("廿/卅/卌 后面还能跟个位（廿五=25、卅二=32）", () => {
    // 这条是真机上抓到的 bug：原先 廿 走的是「临时 = 值」分支，
    // 下一个字直接覆盖它，于是「廿五」算成 5、「卅五」算成 5。
    // 危害在于不报错——只是日期悄悄变成别的日子。
    expect(中文数字转整数("廿五")).toBe(25);
    expect(中文数字转整数("卅二")).toBe(32);
    expect(中文数字转整数("卌一")).toBe(41);
  });

  it("「十」是乘十的倍率，「廿」是完整值（两者处理方式不同）", () => {
    // 修 廿五 时第一版写成 临时 * (十位/10)，把「二十」变成了 2。
    // 十 → 前面的数乘十；廿/卅/卌 → 本身就是完整十位值。
    expect(中文数字转整数("二十")).toBe(20);
    expect(中文数字转整数("三十五")).toBe(35);
    expect(中文数字转整数("九十九")).toBe(99);
  });

  it("无法识别时返回 0，不抛错", () => {
    // 这是刻意的：日期解析失败要回落到「今天」，不能把整个能力打挂
    expect(中文数字转整数("abc")).toBe(0);
    expect(中文数字转整数("")).toBe(0);
    expect(中文数字转整数("一x")).toBe(0);
  });
});

describe("text 解析日期", () => {
  // 冻结到 2026-03-15（周日），与真实时钟解耦
  beforeEach(() => {
    vi.useFakeTimers();
    vi.setSystemTime(new Date(2026, 2, 15, 12, 0, 0));
  });
  afterEach(() => {
    vi.useRealTimers();
  });

  const 取 = (输入: string) => {
    const d = 解析日期(输入);
    return [d.getFullYear(), d.getMonth() + 1, d.getDate()];
  };

  it("今天", () => {
    expect(取("今天")).toEqual([2026, 3, 15]);
  });

  it("昨天 / 前天", () => {
    expect(取("昨天")).toEqual([2026, 3, 14]);
    expect(取("前天")).toEqual([2026, 3, 13]);
  });

  it("明天 / 后天", () => {
    expect(取("明天")).toEqual([2026, 3, 16]);
    expect(取("后天")).toEqual([2026, 3, 17]);
  });

  it("大前天 / 大大前天：每多一个「大」再往前一天", () => {
    expect(取("大前天")).toEqual([2026, 3, 12]);
    expect(取("大大前天")).toEqual([2026, 3, 11]);
  });

  it("大后天 / 大大后天：每多一个「大」再往后一天", () => {
    expect(取("大后天")).toEqual([2026, 3, 18]);
    expect(取("大大后天")).toEqual([2026, 3, 19]);
  });

  it("中文月份：三月五 / 三月五日", () => {
    expect(取("三月五")).toEqual([2026, 3, 5]);
    expect(取("三月五日")).toEqual([2026, 3, 5]);
  });

  it("两位数月份与日期：十二月廿五", () => {
    expect(取("十二月廿五")).toEqual([2026, 12, 25]);
  });

  it("日期里的廿/卅/卌 也认得（三月廿五、十月卅）", () => {
    // 第二个真机 bug：`中文数字转整数` 认 廿，但日期正则的字符集里没有，
    // 于是「三月廿五」静默回落成今天——用户看到的是「历史上的今天」，
    // 完全不知道日期根本没被解析。
    expect(取("三月廿五")).toEqual([2026, 3, 25]);
    expect(取("十月卅")).toEqual([2026, 10, 30]);
    // 「正月」不在月份字符集里（既有设计），用「一月」
    expect(取("一月卅一")).toEqual([2026, 1, 31]);
  });

  it("阿拉伯数字：3月5 / 3月5日", () => {
    expect(取("3月5")).toEqual([2026, 3, 5]);
    expect(取("3月5日")).toEqual([2026, 3, 5]);
  });

  it("无法识别时回落到今天（不抛错）", () => {
    // 静默回落是既有行为；这里锁住它，免得以后改成抛错把能力打挂
    expect(取("随便写的")).toEqual([2026, 3, 15]);
    expect(取("")).toEqual([2026, 3, 15]);
  });

  it("「3月5」显式指定年份时用的是当前年份", () => {
    // 行为依据：源实现用 现在.getFullYear()，不推断「是不是明年」
    expect(解析日期("3月5").getFullYear()).toBe(2026);
  });
});

describe("text 从文本找关键词", () => {
  const 关键词 = ["狗屁不通", "狗屁", "营销号"];

  it("命中一个关键词", () => {
    expect(从文本找关键词("来点营销号", 关键词)).toEqual(["营销号"]);
  });

  it("最长匹配优先：有「狗屁不通」时不会只报「狗屁」", () => {
    expect(从文本找关键词("狗屁不通", 关键词)).toEqual(["狗屁不通"]);
  });

  it("只有「狗屁」时才报「狗屁」", () => {
    expect(从文本找关键词("狗屁东西", 关键词)).toEqual(["狗屁"]);
  });

  it("多个关键词按在**关键词表里**的顺序返回，不按出现顺序", () => {
    // 文本里 营销号 在前，但表里 狗屁不通 在前
    expect(从文本找关键词("营销号 狗屁不通", 关键词)).toEqual(["狗屁不通", "营销号"]);
  });

  it("同一关键词出现多次只返回一次", () => {
    expect(从文本找关键词("营销号营销号营销号", 关键词)).toEqual(["营销号"]);
  });

  it("没有命中返回空数组", () => {
    expect(从文本找关键词("毫不相干", 关键词)).toEqual([]);
  });

  it("空文本返回空数组", () => {
    expect(从文本找关键词("", 关键词)).toEqual([]);
  });

  it("关键词表为空时不崩、返回空", () => {
    expect(从文本找关键词("随便", [])).toEqual([]);
  });
});

describe("text 规范参数", () => {
  it("把 参数文本 补到 文本/输入/主题/日期", () => {
    expect(规范参数({ 参数文本: "狗屁不通" })).toEqual({
      参数文本: "狗屁不通",
      文本: "狗屁不通",
      输入: "狗屁不通",
      主题: "狗屁不通",
      日期: "狗屁不通",
    });
  });

  it("没有 参数文本 时用 原文", () => {
    expect(规范参数({ 原文: "营销号" })).toMatchObject({ 主题: "营销号" });
  });

  it("显式给了某个字段就不覆盖它", () => {
    // 中文指令会带上 参数文本，但调用方显式传了 主题 时要以 主题 为准
    expect(规范参数({ 参数文本: "A", 主题: "B" })).toMatchObject({ 主题: "B" });
  });

  it("非对象原样返回", () => {
    expect(规范参数(null)).toBe(null);
    expect(规范参数(undefined)).toBe(undefined);
    expect(规范参数("字符串")).toBe("字符串");
    expect(规范参数(42)).toBe(42);
  });

  it("没有 参数文本 也没有 原文 时不做补齐", () => {
    expect(规范参数({ 文本: "X" })).toEqual({ 文本: "X" });
  });
});
