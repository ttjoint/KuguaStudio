/**
 * qrcode 模块的参数归一测试。
 *
 * 这里测的都是**「错了也看不出来」**的地方：
 * 二维码生成成功、能扫，但尺寸/边距/纠错级别不对——
 * 肉眼绝对发现不了，只有比对返回值才知道。
 */

import { describe, expect, it } from "vitest";
import { 归一参数 } from "../src/params.js";

describe("文本的键名回落", () => {
  it("优先认 文本", () => {
    expect(归一参数({ 文本: "a" }).文本).toBe("a");
  });

  it("没有 文本 时认 参数文本（聊天框入口）", () => {
    expect(归一参数({ 参数文本: "b" }).文本).toBe("b");
  });

  it("都没有时认 原文（最早那版）", () => {
    expect(归一参数({ 原文: "c" }).文本).toBe("c");
  });

  it("三个都给了时以 文本 为准", () => {
    expect(归一参数({ 文本: "新", 参数文本: "中", 原文: "旧" }).文本).toBe("新");
  });

  it("文本 给了空串时会回落到 参数文本", () => {
    // ?? 只挡 null/undefined，空串会「占位」。
    // 所以 "" 会被 trim 后判空... 等等，这里先 trim 再判空的话，
    // 空串会走回落吗？看实现：`p.文本 ?? p.参数文本` —— 空串不是
    // undefined，所以不会回落，trim 后为空 → 抛错。
    expect(() => 归一参数({ 文本: "", 参数文本: "备用" })).toThrow("缺少 文本");
  });

  it("两端空白被 trim", () => {
    expect(归一参数({ 文本: "  你好  " }).文本).toBe("你好");
  });

  it("只有空白等于没给", () => {
    expect(() => 归一参数({ 文本: "   " })).toThrow("缺少 文本");
  });

  it("完全没有参数就抛错", () => {
    expect(() => 归一参数(undefined)).toThrow("缺少 文本");
    expect(() => 归一参数(null)).toThrow("缺少 文本");
    expect(() => 归一参数({})).toThrow("缺少 文本");
  });
});

describe("尺寸", () => {
  it("默认 300", () => {
    expect(归一参数({ 文本: "x" }).尺寸).toBe(300);
  });

  it("正数照用", () => {
    expect(归一参数({ 文本: "x", 尺寸: 512 }).尺寸).toBe(512);
  });

  it("0 退回默认（0 画不出图）", () => {
    expect(归一参数({ 文本: "x", 尺寸: 0 }).尺寸).toBe(300);
  });

  it("负数退回默认", () => {
    expect(归一参数({ 文本: "x", 尺寸: -100 }).尺寸).toBe(300);
  });

  it("NaN 退回默认", () => {
    expect(归一参数({ 文本: "x", 尺寸: NaN }).尺寸).toBe(300);
  });

  it("Infinity 会被当成正数放行（当前行为）", () => {
    // 严格说该挡掉，但 qrcode 库自己会报错，交给它。
    // 钉住是为了将来有人加了上限时能看到这里的变化。
    expect(归一参数({ 文本: "x", 尺寸: Infinity }).尺寸).toBe(Infinity);
  });

  it("小数不提前取整", () => {
    // qrcode 库自己处理小数。提前 Math.floor 会让
    // 「返回的 width」和「实际图片尺寸」不一致。
    expect(归一参数({ 文本: "x", 尺寸: 300.7 }).尺寸).toBe(300.7);
  });

  it("字符串数字不认（类型必须对）", () => {
    expect(归一参数({ 文本: "x", 尺寸: "512" as unknown as number }).尺寸).toBe(300);
  });
});

describe("边距", () => {
  it("默认 4", () => {
    expect(归一参数({ 文本: "x" }).边距).toBe(4);
  });

  it("0 是合法值，不能退回 4", () => {
    // 这条专门防 `p.边距 || 4` 那种写法：
    // 用户要贴边（0），`||` 会把它换成 4，而图照样生成成功——
    // 从任何角度看都「没坏」，只是不符合要求。
    expect(归一参数({ 文本: "x", 边距: 0 }).边距).toBe(0);
  });

  it("非零数字照用", () => {
    expect(归一参数({ 文本: "x", 边距: 10 }).边距).toBe(10);
  });

  it("负数原样放行（当前行为，由库决定）", () => {
    expect(归一参数({ 文本: "x", 边距: -1 }).边距).toBe(-1);
  });

  it("字符串不认", () => {
    expect(归一参数({ 文本: "x", 边距: "8" as unknown as number }).边距).toBe(4);
  });
});

describe("纠错级别", () => {
  it("默认 M", () => {
    expect(归一参数({ 文本: "x" }).纠错).toBe("M");
  });

  it("四个合法值都认", () => {
    for (const v of ["L", "M", "Q", "H"] as const) {
      expect(归一参数({ 文本: "x", 纠错: v }).纠错).toBe(v);
    }
  });

  it("非法值退回 M 而不是抛错", () => {
    // 用户手打指令时写错一个字母，生成一张能扫的图比报错更有用。
    expect(归一参数({ 文本: "x", 纠错: "X" as never }).纠错).toBe("M");
    expect(归一参数({ 文本: "x", 纠错: "" as never }).纠错).toBe("M");
  });

  it("小写不认（要的就是大写）", () => {
    expect(归一参数({ 文本: "x", 纠错: "q" as never }).纠错).toBe("M");
  });
});

describe("整体返回值", () => {
  it("字段齐全、类型对", () => {
    const r = 归一参数({ 文本: " https://example.com ", 尺寸: 400, 纠错: "H", 边距: 2 });
    expect(r).toEqual({ 文本: "https://example.com", 尺寸: 400, 纠错: "H", 边距: 2 });
  });

  it("全默认时的完整形态", () => {
    expect(归一参数({ 文本: "x" })).toEqual({ 文本: "x", 尺寸: 300, 纠错: "M", 边距: 4 });
  });

  it("不修改入参", () => {
    const 入 = { 文本: "  留白  ", 尺寸: 200 };
    const 快照 = JSON.stringify(入);
    归一参数(入);
    expect(JSON.stringify(入)).toBe(快照);
  });
});
