/**
 * 二维码模块的参数归一。
 *
 * 抽出来的理由：`qrcode.generate` 的处理器里有几处**默认值回落**，
 * 而默认值错了不会报错——只会生成一张「看起来正常但参数不对」的图。
 * 这类问题肉眼极难发现（谁能看出二维码是 300 还是 320？），
 * 只能靠测试钉住。
 *
 * 另外这层要处理「文本」的三个键名回落（`文本` / `参数文本` / `原文`），
 * 那是为了兼容聊天框指令与 MCP 两条入口的历史差异，顺序不能乱。
 */

export type 纠错级别 = "L" | "M" | "Q" | "H";

export interface 原始参数 {
  文本?: string;
  尺寸?: number;
  纠错?: 纠错级别;
  边距?: number;
  参数文本?: string;
  原文?: string;
}

export interface 归一结果 {
  文本: string;
  尺寸: number;
  纠错: 纠错级别;
  边距: number;
}

const 合法纠错: readonly 纠错级别[] = ["L", "M", "Q", "H"];

/**
 * 归一参数。文本为空时抛错（由调用方转成业务失败），其余给默认值。
 */
export function 归一参数(params: unknown): 归一结果 {
  const p = (params ?? {}) as 原始参数;

  // 键名回落顺序是刻意的：`文本` 是新协议，`参数文本` 是聊天框传的，
  // `原文` 是最早那版的叫法。三个都空才算真没给。
  const 文本 = String(p.文本 ?? p.参数文本 ?? p.原文 ?? "").trim();
  if (!文本) throw new Error("缺少 文本");

  // 尺寸只认**正数**。0、负数、NaN 都退回 300。
  // 注意没写 `Math.floor`：`qrcode` 自己会处理小数，
  // 提前取整反而会让「300.5」这种输入的实际尺寸与返回值不匹配。
  const 尺寸 = typeof p.尺寸 === "number" && p.尺寸 > 0 ? p.尺寸 : 300;

  // 边距允许 0（二维码贴边是合法需求），所以判的是 `typeof` 而不是真值。
  // 早期写成 `p.边距 || 4`，用户传 0 会被换成 4——正是那种「看着没坏」的 bug。
  const 边距 = typeof p.边距 === "number" ? p.边距 : 4;

  // 纠错级别只白名单内的值，其余一律按默认 M。
  // 不抛错：用户手打指令时写错一个字母，生成一张能扫的图比报错更有用。
  const 纠错 = 合法纠错.includes(p.纠错 as 纠错级别) ? (p.纠错 as 纠错级别) : "M";

  return { 文本, 尺寸, 纠错, 边距 };
}
